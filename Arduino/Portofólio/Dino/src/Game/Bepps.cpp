#include "Game.h"
#include <Arduino.h>

/*
============================================================
  BEEP: BOTÃO UP
------------------------------------------------------------
  - Som curto e agudo
  - Usado para navegação vertical
============================================================
*/
void Game::beepUp() {
    tone(BUZZER_PIN, 1200, 60);
}

/*
============================================================
  BEEP: BOTÃO OK
------------------------------------------------------------
  - Som médio
  - Usado para confirmar ações
============================================================
*/
void Game::beepOK() {
    tone(BUZZER_PIN, 900, 80);
}

/*
============================================================
  BEEP: BOTÃO BACK
------------------------------------------------------------
  - Som mais grave
  - Usado para voltar atrás
============================================================
*/
void Game::beepBack() {
    tone(BUZZER_PIN, 500, 80);
}

/*
============================================================
  BEEP: MOVIMENTO ENTRE OPÇÕES
------------------------------------------------------------
  - Som rápido
  - Usado para navegar listas
============================================================
*/
void Game::beepMove() {
    tone(BUZZER_PIN, 900, 40);
}

/*
============================================================
  BEEP: AUMENTAR ATRIBUTO
------------------------------------------------------------
  - Som agudo
  - Feedback positivo
============================================================
*/
void Game::beepIncrease() {
    tone(BUZZER_PIN, 1500, 60);
}

/*
============================================================
  BEEP: DIMINUIR ATRIBUTO
------------------------------------------------------------
  - Som grave
  - Feedback negativo
============================================================
*/
void Game::beepDecrease() {
    tone(BUZZER_PIN, 400, 60);
}

/*
============================================================
  BEEP: ALERTA
------------------------------------------------------------
  - Som grave e longo
  - Usado quando algum status está crítico
============================================================
*/
void Game::beepAlert() {
    tone(BUZZER_PIN, 300, 200);
}
